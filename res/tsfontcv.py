#!/usr/bin/env python3
# Extracts the ASCII glyphs (8x16) of Unscii for the Thumbstart loader:
#   tsfontcv.py res/fonts/unscii-16.hex src/thumbstart_font.h
import sys
out = ['// Generated by res/tsfontcv.py from res/fonts/unscii-16.hex (Unscii, 8x16, ASCII only). Do not edit.',
       'static const uint8_t ts_font[95][16] = {']
g = {}
for l in open(sys.argv[1]):
    c, d = l.strip().split(':')
    cp = int(c, 16)
    if 0x20 <= cp <= 0x7E and len(d) == 32:
        g[cp] = bytes.fromhex(d)
assert len(g) == 95
for cp in range(0x20, 0x7F):
    name = "backslash" if chr(cp) == "\\" else chr(cp)
    out.append('  {' + ','.join('0x%02x' % b for b in g[cp]) + '},  // ' + name)
out.append('};')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
