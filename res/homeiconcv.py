# Converts the home screen corner icons of TWiLight Menu++ (GPLv3, quickmenu/gfx:
# cornericons.png and icon_settings.png) to a C header: indexed bitmaps cropped to
# their content, index 0 is transparent (the original uses magenta as key).
# usage: python3 homeiconcv.py cornericons.png icon_settings.png > ../src/res/home_icons.h
import sys, PIL.Image

KEY = (255, 0, 255)
cc = PIL.Image.open(sys.argv[1]).convert("RGB")
st = PIL.Image.open(sys.argv[2]).convert("RGB")

def crop(im, k):
  c = im.crop((0, k * 32, 32, k * 32 + 32))
  px = c.load()
  pts = [(x, y) for y in range(32) for x in range(32) if px[x, y] != KEY]
  return c.crop((min(p[0] for p in pts), min(p[1] for p in pts),
                 max(p[0] for p in pts) + 1, max(p[1] for p in pts) + 1))

def darken(im, f):
  # Same icon with every color scaled towards black (the dark theme version).
  out = im.copy()
  px = out.load()
  for y in range(out.height):
    for x in range(out.width):
      if px[x, y] != KEY:
        px[x, y] = tuple(int(v * f) for v in px[x, y])
  return out

icons = [("SUN", crop(cc, 0)), ("DIM", crop(cc, 1)), ("CLOCK", crop(cc, 2)), ("SETTINGS", crop(st, 0)), ("SETTINGS_DARK", darken(crop(st, 0), 0.45))]

pal = []
for _, im in icons:
  for y in range(im.height):
    for x in range(im.width):
      c = im.getpixel((x, y))
      if c != KEY and c not in pal:
        pal.append(c)
assert len(pal) <= 24, len(pal)   # palette indices 96..119 (HOME_ICON_BASE + 1 ..)

print("// Generated by res/homeiconcv.py from TWiLight Menu++ artwork (GPLv3).")
print("#define HOME_ICON_COLORS %d" % len(pal))
print("static const uint16_t home_icon_pal[HOME_ICON_COLORS] = {")
print("  " + ", ".join("0x%04x" % ((r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10)) for r, g, b in pal))
print("};")
print("enum { %s };" % ", ".join("HOME_ICON_" + n for n, _ in icons))
print("static const struct { uint8_t w, h; const uint8_t *data; } home_icons[] = {")
for n, im in icons:
  print("  { %d, %d, (const uint8_t[]){" % im.size)
  for y in range(im.height):
    print("    " + ",".join("%d" % (0 if im.getpixel((x, y)) == KEY else pal.index(im.getpixel((x, y))) + 1) for x in range(im.width)) + ",")
  print("  } },")
print("};")
